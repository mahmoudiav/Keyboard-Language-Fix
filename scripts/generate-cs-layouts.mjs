/*
 * Generates windows/src/KeyboardLanguageFix.Core/Layouts.g.cs from
 * src/core/layouts.js, so the browser extension and the Windows app can never
 * disagree about what a key produces.
 *
 *   node scripts/generate-cs-layouts.mjs           # write the file
 *   node scripts/generate-cs-layouts.mjs --check   # fail if it is stale
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.join(root, 'src', 'core', 'layouts.js');
const target = path.join(root, 'windows', 'src', 'KeyboardLanguageFix.Core', 'Layouts.g.cs');

const require = createRequire(import.meta.url);
const layouts = require(source);
const digest = crypto.createHash('sha256')
  .update(fs.readFileSync(source)).digest('hex').slice(0, 16);

/** C# string literal with every non-ASCII character escaped, so the file is pure ASCII. */
function csString(value) {
  let out = '';
  for (const ch of value) {
    const code = ch.codePointAt(0);
    if (ch === '"') out += '\\"';
    else if (ch === '\\') out += '\\\\';
    else if (code >= 0x20 && code < 0x7f) out += ch;
    else if (code > 0xffff) {
      // surrogate pair
      const high = Math.floor((code - 0x10000) / 0x400) + 0xd800;
      const low = ((code - 0x10000) % 0x400) + 0xdc00;
      out += `\\u${high.toString(16).padStart(4, '0')}\\u${low.toString(16).padStart(4, '0')}`;
    } else out += `\\u${code.toString(16).padStart(4, '0')}`;
  }
  return `"${out}"`;
}

function entries(table) {
  return Object.entries(table)
    .map(([key, value]) => `                { ${csString(key)}, ${csString(value)} },`)
    .join('\n');
}

const blocks = layouts.LAYOUTS.map((layout) => `        private static Layout ${
  layout.id.toUpperCase()}() => new Layout(
            id: ${csString(layout.id)},
            name: ${csString(layout.name)},
            nameLocal: ${csString(layout.nameLocal)},
            rightToLeft: ${layout.rtl ? 'true' : 'false'},
            shiftFallback: ${layout.shiftFallback ? 'true' : 'false'},
            scriptPattern: ${csString(layout.script.source)},
            baseLayer: new Dictionary<string, string>(StringComparer.Ordinal)
            {
${entries(layout.base)}
            },
            shiftLayer: new Dictionary<string, string>(StringComparer.Ordinal)
            {
${entries(layout.shift)}
            });`).join('\n\n');

const file = `// <auto-generated>
//     Generated from src/core/layouts.js by scripts/generate-cs-layouts.mjs.
//     Source digest: ${digest}
//     Do not edit by hand: edit the JavaScript table and re-run the generator,
//     so the browser extension and this app stay in agreement.
// </auto-generated>
using System;
using System.Collections.Generic;

namespace KeyboardLanguageFix.Core
{
    /// <summary>The built-in keyboard layout tables.</summary>
    public static partial class Layouts
    {
        /// <summary>Digest of the JavaScript table these entries were generated from.</summary>
        public const string SourceDigest = "${digest}";

        private static IReadOnlyList<Layout> Build() => new[]
        {
${layouts.LAYOUTS.map((l) => `            ${l.id.toUpperCase()}(),`).join('\n')}
        };

${blocks}
    }
}
`;

const check = process.argv.includes('--check');
const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;

if (check) {
  if (current !== file) {
    console.error('Layouts.g.cs is stale — run: node scripts/generate-cs-layouts.mjs');
    process.exit(1);
  }
  console.log('Layouts.g.cs is up to date (digest ' + digest + ')');
} else {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, file);
  console.log(`wrote ${path.relative(root, target)} (${layouts.LAYOUTS.length} layouts, digest ${digest})`);
}
